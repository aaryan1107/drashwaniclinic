// Builds the bundled term index (src/data/terms.seed.json) from docs/seed/*.txt and the NLEM medicine list,
// and optionally SQL for the `terms` table (--sql -> supabase/seed_terms.sql). Run: node scripts/build-seed.mjs [--sql]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lines = (file) => readFileSync(join(root, file), "utf8").split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("#"));
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 80);
const syn = (s = "") => s.split(";").map((x) => x.trim()).filter(Boolean);
const terms = [];
const seen = new Set();
const add = (type, system, code, display, synonyms) => {
  const id = `${type}:${slug(code && type === "diagnosis" ? `${code}-${display}` : display)}`;
  if (seen.has(id)) throw new Error(`Duplicate seed term ${id}`);
  seen.add(id);
  terms.push({ id, type, code_system: system, code, display, synonyms });
};

for (const l of lines("docs/seed/symptoms.txt")) { const [d, s] = l.split("|").map((x) => x.trim()); add("symptom", "LOCAL", "", d, syn(s)); }
for (const l of lines("docs/seed/findings.txt")) { const [d, s] = l.split("|").map((x) => x.trim()); add("finding", "LOCAL", "", d, syn(s)); }
for (const l of lines("docs/seed/lab_tests.txt")) {
  const [k, d, s] = l.split("|").map((x) => x.trim());
  add(k === "P" ? "lab_panel" : "lab_test", "LOCAL", "", d, syn(s));
}
for (const l of lines("docs/seed/diagnoses.txt")) { const [c, d, s] = l.split("|").map((x) => x.trim()); add("diagnosis", "ICD10", c, d, syn(s)); }
for (const name of JSON.parse(readFileSync(join(root, "src/medicine-catalog.json"), "utf8"))) add("medicine", "LOCAL", "", name, []);

writeFileSync(join(root, "src/data/terms.seed.json"), JSON.stringify(terms.map((t) => [t.id, t.type, t.code_system, t.code, t.display, t.synonyms])));
console.log(`terms.seed.json: ${terms.length} terms`, Object.entries(terms.reduce((a, t) => ({ ...a, [t.type]: (a[t.type] || 0) + 1 }), {})));

if (process.argv.includes("--sql")) {
  const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
  const rows = terms.map((t) => `(${q(t.id)},${q(t.type)},${q(t.code_system)},${q(t.code)},${q(t.display)},array[${t.synonyms.map(q).join(",")}]::text[],true,'active')`);
  writeFileSync(join(root, "supabase/seed_terms.sql"),
    `-- Generated by scripts/build-seed.mjs. Needs doctor review before real use.\ninsert into public.terms (id,type,code_system,code,display,synonyms,is_global,status) values\n${rows.join(",\n")}\non conflict (id) do update set display = excluded.display, synonyms = excluded.synonyms, code = excluded.code;\n`);
  console.log("wrote supabase/seed_terms.sql");
}
